#!/usr/bin/env python3
"""Validate canonical design tokens and emit dependency-free Swift constants."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'ui/Packages/DIPDesignSystem/Sources/DIPDesignSystem/Tokens.generated.swift'


def validate(tokens):
    if tokens['version'] != 1:
        raise ValueError('Unsupported token version')
    if tokens['supportedModes'] != ['light']:
        raise ValueError('Only reviewed light-mode tokens are currently specified')
    if tokens['darkModeStatus'] != 'pending-design-review':
        raise ValueError('Dark mode needs a separate reviewed implementation')
    color = tokens['color']
    for name, item in color['primitive'].items():
        if not re.fullmatch(r'#[0-9A-F]{6}', item['value']):
            raise ValueError(f'Invalid RGB token: {name}')
    for name, item in color['semantic'].items():
        if item['alias'] not in color['primitive']:
            raise ValueError(f'Unknown primitive alias: {name}')
    for group in ('spacing', 'radius'):
        for name, item in tokens[group].items():
            if isinstance(item['value'], bool) or not isinstance(item['value'], (int, float)) or item['value'] < 0:
                raise ValueError(f'Invalid numeric token: {group}.{name}')
    if tokens['spacing']['minimumTouchTarget']['value'] < 44:
        raise ValueError('Minimum touch target must be at least 44 pt')
    for name, item in tokens['typography'].items():
        if not item['family'] or item['referenceSize'] <= 0:
            raise ValueError(f'Invalid typography token: {name}')
    groups = [color['primitive'], color['semantic'], tokens['spacing'], tokens['radius'], tokens['typography']]
    for group in groups:
        for name, item in group.items():
            if not re.fullmatch(r'[a-z][A-Za-z0-9]*', name):
                raise ValueError(f'Invalid Swift token name: {name}')
            if item['origin'] not in ('figma', 'proposal'):
                raise ValueError(f'Unknown token provenance: {name}')


def render(tokens):
    validate(tokens)
    lines = [
        '// Generated by scripts/generate-tokens.py. Do not edit.',
        'import Foundation', '',
        'public struct RGBColor: Equatable, Sendable {',
        '    public let hex: String',
        '    public let red: Double',
        '    public let green: Double',
        '    public let blue: Double',
        '',
        '    internal init(hex: String, red: Double, green: Double, blue: Double) {',
        '        self.hex = hex',
        '        self.red = red',
        '        self.green = green',
        '        self.blue = blue',
        '    }',
        '}', '',
        '/// Family names and sizes are references; font files are not bundled.',
        '/// Use Dynamic Type text styles when implementing SwiftUI components.',
        'public struct TypographyReference: Equatable, Sendable {',
        '    public let family: String',
        '    public let referenceSize: Double',
        '}', '',
        'public enum DIPTokens {',
        '    public static let supportedModes = ["light"]',
        '    public static let darkModeStatus = "pending-design-review"',
        '    public enum Color {'
    ]
    for name, item in tokens['color']['semantic'].items():
        value = tokens['color']['primitive'][item['alias']]['value']
        rgb = [int(value[i:i + 2], 16) for i in (1, 3, 5)]
        lines += [f'        /// Source: {item["origin"]}.', f'        public static let {name} = RGBColor(hex: "{value}", red: {rgb[0]}.0 / 255.0, green: {rgb[1]}.0 / 255.0, blue: {rgb[2]}.0 / 255.0)']
    lines.append('    }')
    for group in ('spacing', 'radius'):
        lines.append(f'    public enum {group.capitalize()} {{')
        for name, item in tokens[group].items():
            lines.append(f'        public static let {name}: Double = {item["value"]}')
        lines.append('    }')
    lines.append('    public enum Typography {')
    for name, item in tokens['typography'].items():
        lines.append(f'        public static let {name} = TypographyReference(family: {json.dumps(item["family"])}, referenceSize: {item["referenceSize"]})')
    lines += ['    }', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    contents = render(json.loads((ROOT / 'ui/DesignSystem/tokens.json').read_text()))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != contents:
            raise SystemExit('Stale design tokens: run python3 scripts/generate-tokens.py')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(contents)


if __name__ == '__main__':
    main()
