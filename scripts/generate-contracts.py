#!/usr/bin/env python3
"""Generate transport types from the versioned schema; no third-party dependencies."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(check=False):
    schema = json.loads((ROOT / 'contracts/v1/models.schema.json').read_text())
    typescript = ['// Generated by scripts/generate-contracts.py. Do not edit.\n']
    swift = ['// Generated by scripts/generate-contracts.py. Do not edit.\nimport Foundation\n']

    def field_type(spec, language):
        if '$ref' in spec:
            return spec['$ref'].split('/')[-1]
        kind = spec['type']
        nullable = isinstance(kind, list)
        if nullable:
            kind = next(x for x in kind if x != 'null')
        if kind == 'array':
            item = field_type(spec['items'], language)
            result = f'[{item}]' if language == 'swift' else f'Array<{item}>'
        elif spec.get('format') == 'date-time':
            result = 'Date' if language == 'swift' else 'string'
        elif 'enum' in spec and language == 'ts':
            result = ' | '.join(json.dumps(x) for x in spec['enum'])
        else:
            result = ({'string': 'String', 'integer': 'Int', 'number': 'Double', 'boolean': 'Bool'} if language == 'swift' else {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean'})[kind]
        return result + (('?' if language == 'swift' else ' | null') if nullable else '')

    for name, definition in schema['$defs'].items():
        typescript.append(f'export interface {name} {{')
        swift.append(f'public struct {name}: Codable, Equatable, Sendable {{')
        arguments = []
        assignments = []
        for field, spec in definition['properties'].items():
            optional = field not in definition['required']
            ts = field_type(spec, 'ts')
            sw = field_type(spec, 'swift')
            if optional and not sw.endswith('?'):
                sw += '?'
            typescript.append(f'  {field}{"?" if optional else ""}: {ts};')
            swift.append(f'    public var {field}: {sw}')
            arguments.append(f'{field}: {sw}' + (' = nil' if sw.endswith('?') else ''))
            assignments.append(f'        self.{field} = {field}')
        typescript.append('}\n')
        swift += ['', '    public init(' + ', '.join(arguments) + ') {', *assignments, '    }', '}\n']

    outputs = {
        'gcp/functions/src/generated/models.ts': '\n'.join(typescript),
        'ui/Packages/DIPContracts/Sources/DIPContracts/Models.swift': '\n'.join(swift),
        'ui/Packages/DIPContracts/Tests/DIPContractsTests/Fixtures/happy-path.json': (ROOT / 'contracts/v1/fixtures/happy-path.json').read_text(),
    }
    stale = []
    for path, contents in outputs.items():
        target = ROOT / path
        if check:
            if not target.exists() or target.read_text() != contents:
                stale.append(path)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(contents)
    if stale:
        raise SystemExit('Stale generated contracts: ' + ', '.join(stale))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
